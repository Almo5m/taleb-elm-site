-- 1) جدول الأحداث
create table if not exists site_events (
  id           bigint generated by default as identity primary key,
  created_at   timestamptz not null default now(),
  visitor_id   text not null,
  event_type   text not null check (event_type in (
                 'page_view', 'reached_download', 'download_clicked', 'whatsapp_followed'
               )),
  page         text,
  referrer     text,
  user_agent   text
);

create index if not exists site_events_event_type_idx on site_events (event_type);
create index if not exists site_events_visitor_id_idx on site_events (visitor_id);
create index if not exists site_events_created_at_idx on site_events (created_at);

-- 2) تأمين الجدول: أي حد معاه مفتاح anon (اللي هيتحط في كود الموقع، وهو ظاهر
--    لأي حد يفتح الموقع) يقدر بس "يسجّل" حدث جديد، ومينفعش يقرا أي بيانات.
alter table site_events enable row level security;

drop policy if exists "allow insert from anyone" on site_events;
create policy "allow insert from anyone"
  on site_events for insert
  to anon
  with check (true);

-- ملحوظة: مفيش أي policy لقراءة الجدول، يعني حتى لو حد فتح مفتاح الـ anon
-- من كود الموقع مش هيقدر يقرا بيانات الزوار خالص.

